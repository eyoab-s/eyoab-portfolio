export function buildMask(text: string, cols: number, center = false): Uint8Array {
  const mask = new Uint8Array(cols * ROWS);
  const top = Math.floor((ROWS - GLYPH_H) / 2);
  const total = text.length * ADVANCE - 1;
  let x = center ? Math.max(0, Math.floor((cols - total) / 2)) : 1;

  for (const ch of text) {
    if (x + GLYPH_W > cols) break;
    const glyph = FONT[ch] ?? FONT[" "];
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (glyph[r] & (1 << (GLYPH_W - 1 - c))) {
          mask[(top + r) * cols + x + c] = 1;
        }
      }
    }
    x += ADVANCE;
  }
  return mask;
}